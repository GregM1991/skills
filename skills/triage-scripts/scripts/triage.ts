#!/usr/bin/env bun
// Deterministic parts of the triage skill: build the attention queue and apply an outcome.
// The agent keeps the judgment (category, state, briefs, grilling). This script only talks to GitHub through `gh`.
import { readFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

export const DISCLAIMER = "> *This was generated by AI during triage.*";
export const STATE_ROLES = ["needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "wontfix"] as const;
export const CATEGORY_ROLES = ["bug", "enhancement"] as const;
const ALL_ROLES = [...STATE_ROLES, ...CATEGORY_ROLES] as const;
const INTERNAL_ASSOCIATIONS = new Set(["OWNER", "MEMBER", "COLLABORATOR"]);
const COMMENT_REQUIRED: ReadonlySet<StateRole> = new Set(["needs-info", "wontfix"]);
const EXCERPT_LIMIT = 160;

export type StateRole = (typeof STATE_ROLES)[number];
export type CategoryRole = (typeof CATEGORY_ROLES)[number];
type Role = (typeof ALL_ROLES)[number];
export type LabelMap = Record<Role, string>;

export type GhIssue = {
	number: number;
	title: string;
	html_url: string;
	state: string;
	body: string | null;
	user: { login: string } | null;
	author_association: string;
	labels: Array<{ name: string } | string>;
	created_at: string;
	pull_request?: unknown;
};

export type GhComment = {
	user: { login: string } | null;
	body: string | null;
	created_at: string;
	html_url: string;
};

export type Gh = {
	get(apiPath: string): Promise<unknown>;
	getAll(apiPath: string): Promise<unknown[]>;
	send(method: "POST" | "PATCH" | "DELETE", apiPath: string, body?: unknown): Promise<unknown>;
};

// ---------- config ----------

export function parseLabelMap(markdown: string | null): { map: LabelMap; mapped: Role[] } {
	const map = Object.fromEntries(ALL_ROLES.map((role) => [role, role])) as LabelMap;
	const mapped: Role[] = [];
	if (markdown === null) return { map, mapped };
	for (const line of markdown.split("\n")) {
		const cells = line.split("|").map((cell) => cell.trim());
		if (cells.length < 4) continue;
		const role = cells[1].replace(/^`|`$/g, "") as Role;
		const label = cells[2].replace(/^`|`$/g, "");
		if (!ALL_ROLES.includes(role) || label.length === 0) continue;
		map[role] = label;
		mapped.push(role);
	}
	return { map, mapped };
}

export function prsInScope(issueTrackerMarkdown: string | null): boolean {
	if (issueTrackerMarkdown === null) return false;
	return /PRs as a request surface:?\**:?\s*yes/i.test(issueTrackerMarkdown);
}

async function readOptional(filePath: string): Promise<string | null> {
	try {
		return await readFile(filePath, "utf8");
	} catch {
		return null;
	}
}

// ---------- shared helpers ----------

function labelNames(issue: GhIssue): string[] {
	return issue.labels.map((label) => (typeof label === "string" ? label : label.name));
}

function rolesOn<R extends Role>(issue: GhIssue, roles: readonly R[], map: LabelMap): R[] {
	const names = new Set(labelNames(issue));
	return roles.filter((role) => names.has(map[role]));
}

function summarize(issue: GhIssue) {
	const body = (issue.body ?? "").replace(/\s+/g, " ").trim();
	return {
		kind: issue.pull_request ? "pr" : "issue",
		number: issue.number,
		title: issue.title,
		url: issue.html_url,
		author: issue.user?.login ?? null,
		createdAt: issue.created_at,
		labels: labelNames(issue),
		excerpt: body.length > EXCERPT_LIMIT ? `${body.slice(0, EXCERPT_LIMIT)}…` : body,
	};
}

export function withDisclaimer(body: string): string {
	const trimmed = body.trim();
	return trimmed.startsWith(DISCLAIMER) ? trimmed : `${DISCLAIMER}\n\n${trimmed}`;
}

function isTriageComment(comment: GhComment): boolean {
	const body = comment.body ?? "";
	return body.includes(DISCLAIMER) || /^##\s+Triage Notes/m.test(body);
}

// ---------- queue ----------

export function reporterActivity(issue: GhIssue, comments: GhComment[]) {
	const reporter = issue.user?.login;
	const ordered = [...comments].sort((a, b) => a.created_at.localeCompare(b.created_at));
	const lastNotes = ordered.filter(isTriageComment).at(-1) ?? null;
	const replies = ordered.filter(
		(comment) => comment.user?.login === reporter && (lastNotes === null || comment.created_at > lastNotes.created_at),
	);
	return {
		active: replies.length > 0,
		lastTriageNotesAt: lastNotes?.created_at ?? null,
		reporterRepliedAt: replies.at(-1)?.created_at ?? null,
	};
}

export async function buildQueue(gh: Gh, repository: string, map: LabelMap, includePrs: boolean) {
	const all = (await gh.getAll(`repos/${repository}/issues?state=open&per_page=100`)) as GhIssue[];
	const items = all
		.filter((issue) => !issue.pull_request || (includePrs && !INTERNAL_ASSOCIATIONS.has(issue.author_association)))
		.sort((a, b) => a.created_at.localeCompare(b.created_at));

	const conflicts = [];
	const unlabeled = [];
	const needsTriage = [];
	const needsInfoActive = [];
	let skippedWayfinder = 0;
	for (const issue of items) {
		const states = rolesOn(issue, STATE_ROLES, map);
		// Wayfinder maps and tickets have their own workflow; they are triage work only once given a state role.
		if (states.length === 0 && labelNames(issue).some((name) => name.startsWith("wayfinder:"))) {
			skippedWayfinder += 1;
			continue;
		}
		if (states.length > 1) conflicts.push({ ...summarize(issue), stateRoles: states });
		else if (states.length === 0) unlabeled.push(summarize(issue));
		else if (states[0] === "needs-triage") needsTriage.push(summarize(issue));
		else if (states[0] === "needs-info") {
			const comments = (await gh.getAll(`repos/${repository}/issues/${issue.number}/comments?per_page=100`)) as GhComment[];
			const activity = reporterActivity(issue, comments);
			if (activity.active) needsInfoActive.push({ ...summarize(issue), ...activity });
		}
	}

	return {
		repository,
		fetchedAt: new Date().toISOString(),
		prsInScope: includePrs,
		skippedWayfinder,
		counts: {
			conflicts: conflicts.length,
			unlabeled: unlabeled.length,
			needsTriage: needsTriage.length,
			needsInfoActive: needsInfoActive.length,
		},
		conflicts,
		unlabeled,
		needsTriage,
		needsInfoActive,
	};
}

// ---------- apply ----------

export type ApplyRequest = {
	number: number;
	state: StateRole;
	category?: CategoryRole;
	comment?: string;
	allowConflict?: boolean;
	dryRun?: boolean;
};

export function planApply(issue: GhIssue, map: LabelMap, request: ApplyRequest) {
	const errors: string[] = [];
	const warnings: string[] = [];
	const states = rolesOn(issue, STATE_ROLES, map);
	const categories = rolesOn(issue, CATEGORY_ROLES, map);

	if (states.length > 1 && !request.allowConflict) {
		errors.push(
			`State roles conflict (${states.join(", ")}). Ask the maintainer, then rerun with --allow-conflict to replace them.`,
		);
	}
	if (COMMENT_REQUIRED.has(request.state) && !request.comment?.trim()) {
		errors.push(`State "${request.state}" needs a comment. Pass --comment-file.`);
	}
	if (!request.category && categories.length === 0) warnings.push("No category role on this item. Pass --category.");
	if (!request.category && categories.length > 1) warnings.push(`Several category roles: ${categories.join(", ")}.`);
	if (issue.state !== "open" && request.state !== "wontfix") warnings.push("This item is closed. The script does not reopen it.");

	const removeLabels = states.filter((role) => role !== request.state).map((role) => map[role]);
	const addLabels = states.includes(request.state) ? [] : [map[request.state]];
	if (request.category) {
		removeLabels.push(...categories.filter((role) => role !== request.category).map((role) => map[role]));
		if (!categories.includes(request.category)) addLabels.push(map[request.category]);
	}

	return {
		kind: issue.pull_request ? "pr" : "issue",
		number: issue.number,
		url: issue.html_url,
		from: { states, categories },
		removeLabels,
		addLabels,
		comment: request.comment?.trim() ? withDisclaimer(request.comment) : null,
		close: request.state === "wontfix" && issue.state === "open",
		errors,
		warnings,
	};
}

export function verifyApplied(issue: GhIssue, map: LabelMap, request: ApplyRequest): string[] {
	const problems: string[] = [];
	const states = rolesOn(issue, STATE_ROLES, map);
	const categories = rolesOn(issue, CATEGORY_ROLES, map);
	if (states.length !== 1 || states[0] !== request.state) {
		problems.push(`Expected state role "${request.state}", found [${states.join(", ")}].`);
	}
	if (request.category && (categories.length !== 1 || categories[0] !== request.category)) {
		problems.push(`Expected category role "${request.category}", found [${categories.join(", ")}].`);
	}
	if (request.state === "wontfix" && issue.state !== "closed") problems.push("Expected the item to be closed.");
	return problems;
}

export async function applyOutcome(gh: Gh, repository: string, map: LabelMap, request: ApplyRequest) {
	const base = `repos/${repository}/issues/${request.number}`;
	const issue = (await gh.get(base)) as GhIssue;
	const plan = planApply(issue, map, request);
	if (plan.errors.length > 0) return { status: "refused" as const, plan };
	if (request.dryRun) return { status: "planned" as const, plan };

	for (const label of plan.removeLabels) {
		await gh.send("DELETE", `${base}/labels/${encodeURIComponent(label)}`);
	}
	if (plan.addLabels.length > 0) await gh.send("POST", `${base}/labels`, { labels: plan.addLabels });
	let commentUrl: string | null = null;
	if (plan.comment) {
		const posted = (await gh.send("POST", `${base}/comments`, { body: plan.comment })) as { html_url?: string };
		commentUrl = posted.html_url ?? null;
	}
	if (plan.close) {
		await gh.send("PATCH", base, issue.pull_request ? { state: "closed" } : { state: "closed", state_reason: "not_planned" });
	}

	const after = (await gh.get(base)) as GhIssue;
	const problems = verifyApplied(after, map, request);
	return {
		status: problems.length === 0 ? ("applied" as const) : ("unverified" as const),
		plan,
		commentUrl,
		labelsNow: labelNames(after),
		stateNow: after.state,
		problems,
	};
}

// ---------- gh runner ----------

async function runGh(args: string[], input?: string): Promise<string> {
	const child = Bun.spawn(["gh", ...args], {
		stdin: input === undefined ? "ignore" : new Blob([input]),
		stdout: "pipe",
		stderr: "pipe",
	});
	const [stdout, stderr, code] = await Promise.all([
		new Response(child.stdout).text(),
		new Response(child.stderr).text(),
		child.exited,
	]);
	if (code !== 0) throw new Error(`gh ${args.slice(0, 3).join(" ")} failed: ${stderr.trim() || stdout.trim()}`);
	return stdout;
}

export const realGh: Gh = {
	async get(apiPath) {
		return JSON.parse(await runGh(["api", apiPath]));
	},
	async getAll(apiPath) {
		const pages = JSON.parse(await runGh(["api", "--paginate", "--slurp", apiPath])) as unknown[][];
		return pages.flat();
	},
	async send(method, apiPath, body) {
		const args = ["api", "--method", method, apiPath];
		if (body !== undefined) args.push("--input", "-");
		const out = await runGh(args, body === undefined ? undefined : JSON.stringify(body));
		return out.trim() ? JSON.parse(out) : null;
	},
};

// ---------- CLI ----------

const USAGE = `Usage:
  triage.ts queue [--repo owner/repo] [--config-dir docs/agents] [--prs | --no-prs]
  triage.ts apply <number> --state <role> [--category bug|enhancement] [--comment-file path]
                  [--allow-conflict] [--dry-run] [--repo owner/repo] [--config-dir docs/agents]

State roles: ${STATE_ROLES.join(", ")}
Exit codes: 0 done, 1 error or unverified result, 2 refused (read "errors").`;

async function main(argv: string[]): Promise<number> {
	const { values, positionals } = parseArgs({
		args: argv,
		allowPositionals: true,
		options: {
			repo: { type: "string" },
			"config-dir": { type: "string", default: "docs/agents" },
			prs: { type: "boolean" },
			"no-prs": { type: "boolean" },
			state: { type: "string" },
			category: { type: "string" },
			"comment-file": { type: "string" },
			"allow-conflict": { type: "boolean", default: false },
			"dry-run": { type: "boolean", default: false },
			help: { type: "boolean", default: false },
		},
	});
	const [command, target] = positionals;
	if (values.help || !command) {
		console.log(USAGE);
		return values.help ? 0 : 1;
	}

	const configDir = path.resolve(values["config-dir"]!);
	const labelFile = await readOptional(path.join(configDir, "triage-labels.md"));
	const trackerFile = await readOptional(path.join(configDir, "issue-tracker.md"));
	const { map, mapped } = parseLabelMap(labelFile);
	const repository = values.repo ?? (await runGh(["repo", "view", "--json", "nameWithOwner", "-q", ".nameWithOwner"])).trim();
	const config = {
		labelMap: labelFile === null ? "missing: using canonical names (run /setup-matt-pocock-skills)" : `${mapped.length} roles mapped`,
	};

	if (command === "queue") {
		const includePrs = values.prs ? true : values["no-prs"] ? false : prsInScope(trackerFile);
		console.log(JSON.stringify({ ...config, ...(await buildQueue(realGh, repository, map, includePrs)) }, null, 2));
		return 0;
	}

	if (command === "apply") {
		const number = Number(target);
		if (!Number.isInteger(number) || number <= 0) throw new Error("apply needs an issue or PR number.");
		if (!STATE_ROLES.includes(values.state as StateRole)) throw new Error(`--state must be one of: ${STATE_ROLES.join(", ")}.`);
		if (values.category && !CATEGORY_ROLES.includes(values.category as CategoryRole)) {
			throw new Error(`--category must be one of: ${CATEGORY_ROLES.join(", ")}.`);
		}
		const result = await applyOutcome(realGh, repository, map, {
			number,
			state: values.state as StateRole,
			category: values.category as CategoryRole | undefined,
			comment: values["comment-file"] ? await readFile(values["comment-file"], "utf8") : undefined,
			allowConflict: values["allow-conflict"],
			dryRun: values["dry-run"],
		});
		console.log(JSON.stringify({ repository, ...config, ...result }, null, 2));
		return result.status === "refused" ? 2 : result.status === "unverified" ? 1 : 0;
	}

	console.error(USAGE);
	return 1;
}

if (import.meta.main) {
	main(process.argv.slice(2))
		.then((code) => process.exit(code))
		.catch((error) => {
			console.error(error instanceof Error ? error.message : String(error));
			process.exit(1);
		});
}
